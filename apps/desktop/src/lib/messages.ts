export type MessageKey = keyof typeof TR;

export const MESSAGE_TABLES: Record<UiLanguage, Record<MessageKey, string>> = { tr: TR, en: EN };

export function dateLocale(language: UiLanguage): string {
  return language === 'en' ? 'en-US' : 'tr-TR';
}

export function translate(
  language: UiLanguage,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  let text = (MESSAGE_TABLES[language] ?? MESSAGE_TABLES.tr)[key] ?? MESSAGE_TABLES.tr[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

